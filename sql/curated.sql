CREATE OR REPLACE TABLE
    GOLDSALES_DB.CURATED.FACT_GOLD_SALES AS

SELECT
    YEAR,
    MONTH,
    SALES_COUNTRY_CODE,
    CURRENCYCODE,
    SUM(TOTAL_SALES) AS TOTAL_SALES,
    SUM(TOTAL_SALES_USD) AS TOTAL_SALES_USD,
    SUM(TOTAL_UNITS) AS TOTAL_UNITS,
    SUM(TXN_ID_COUNT) AS TXN_ID_COUNT
FROM GOLDSALES_DB.CLEANSED.GOLD_SALES_CLEANSED
GROUP BY
    YEAR,
    MONTH,
    SALES_COUNTRY_CODE,
    CURRENCYCODE;
