CREATE OR REPLACE TABLE
    GOLDSALES_DB.CLEANSED.GOLD_SALES_CLEANSED AS

WITH CONVERTED AS (
    SELECT
        TRY_TO_NUMBER(TRIM(YEAR)) AS YEAR,
        TRY_TO_NUMBER(TRIM(MONTH)) AS MONTH,
        UPPER(TRIM(SALES_COUNTRY_CODE))
            AS SALES_COUNTRY_CODE,
        UPPER(TRIM(CURRENCYCODE)) AS CURRENCYCODE,
        TRY_TO_DECIMAL(TRIM(TOTAL_SALES), 38, 4)
            AS TOTAL_SALES,
        TRY_TO_DECIMAL(TRIM(TOTAL_SALES_USD), 38, 2)
            AS TOTAL_SALES_USD,
        TRY_TO_NUMBER(TRIM(TOTAL_UNITS)) AS TOTAL_UNITS,
        TRY_TO_NUMBER(TRIM(TXN_ID_COUNT)) AS TXN_ID_COUNT
    FROM GOLDSALES_DB.RAW.GOLD_SALES_RAW
)
SELECT
    YEAR,
    MONTH,
    SALES_COUNTRY_CODE,
    CURRENCYCODE,
    TOTAL_SALES,
    TOTAL_SALES_USD,
    TOTAL_UNITS,
    TXN_ID_COUNT
FROM CONVERTED
WHERE YEAR BETWEEN 2000 AND 2100
  AND MONTH BETWEEN 1 AND 12
  AND SALES_COUNTRY_CODE IS NOT NULL
  AND SALES_COUNTRY_CODE <> ''
  AND CURRENCYCODE IS NOT NULL
  AND CURRENCYCODE <> ''
  AND TOTAL_SALES IS NOT NULL
  AND TOTAL_SALES_USD IS NOT NULL
  AND TOTAL_UNITS IS NOT NULL
  AND TXN_ID_COUNT IS NOT NULL
  AND TOTAL_SALES >= 0
  AND TOTAL_SALES_USD >= 0
  AND TOTAL_UNITS >= 0
  AND TXN_ID_COUNT >= 0
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY
        YEAR,
        MONTH,
        SALES_COUNTRY_CODE,
        CURRENCYCODE,
        TOTAL_SALES,
        TOTAL_SALES_USD,
        TOTAL_UNITS,
        TXN_ID_COUNT
    ORDER BY YEAR
) = 1;
