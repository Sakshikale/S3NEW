
CREATE DATABASE IF NOT EXISTS GOLDSALES_DB;

CREATE SCHEMA IF NOT EXISTS GOLDSALES_DB.RAW;
CREATE SCHEMA IF NOT EXISTS GOLDSALES_DB.CLEANSED;
CREATE SCHEMA IF NOT EXISTS GOLDSALES_DB.CURATED;

CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE FILE FORMAT
    GOLDSALES_DB.RAW.GOLD_SALES_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('NULL', 'null', '');




CREATE TABLE IF NOT EXISTS
    GOLDSALES_DB.RAW.GOLD_SALES_RAW (
        YEAR VARCHAR,
        MONTH VARCHAR,
        SALES_COUNTRY_CODE VARCHAR,
        CURRENCYCODE VARCHAR,
        TOTAL_SALES VARCHAR,
        TOTAL_SALES_USD VARCHAR,
        TOTAL_UNITS VARCHAR,
        TXN_ID_COUNT VARCHAR,
        LOAD_TIMESTAMP TIMESTAMP_NTZ
            DEFAULT CURRENT_TIMESTAMP()
    );
