CREATE OR REPLACE VIEW
    GOLDSALES_DB.CURATED.VW_GOLD_SALES_REPORT AS

SELECT
    YEAR,
    MONTH,
    SALES_COUNTRY_CODE,
    CURRENCYCODE,
    ROUND(TOTAL_SALES_1, 0) AS TOTAL_SALES_1,
    ROUND(TOTAL_SALES_USD, 0) AS TOTAL_SALES_USD,
    TOTAL_UNITS,
    TXN_ID_COUNT
FROM GOLDSALES_DB.CURATED.FACT_GOLD_SALES;
